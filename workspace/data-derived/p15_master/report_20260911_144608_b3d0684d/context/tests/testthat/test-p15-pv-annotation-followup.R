testthat::test_that("interest sensitivity preserves principal and first-year terms",{
  f<-p15_analysis_schedule(2,3.5,1)
  u<-p15_interest_step(f,2,1)
  testthat::expect_equal(u$principal,f$principal)
  testthat::expect_equal(u$interest[1],f$interest[1])
  testthat::expect_equal(u$interest[-1],f$opening_balance[-1]*.03*f$period_length[-1])
  testthat::expect_equal(p15_interest_step(f,2,0),f)
  z<-p15_interest_step(f,2,-3)
  testthat::expect_equal(z$interest[-1],rep(0,nrow(f)-1))
  testthat::expect_gt(p15_stream_pv(u,6),p15_stream_pv(f,6))
  b<-p15_analysis_schedule(0,2,2)
  testthat::expect_equal(p15_interest_step(b,0,1)$interest,c(0,1))
  s<-p15_analysis_schedule(2,.5,.5)
  testthat::expect_equal(p15_interest_step(s,2,1),s)
})
