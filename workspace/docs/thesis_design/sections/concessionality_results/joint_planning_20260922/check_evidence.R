read_stage <- function(stage, name) {
  p <- file.path(run$stages[[stage]]$dir, name)
  inputs <<- unique(c(inputs,p))
  read.csv(p, check.names=FALSE, stringsAsFactors=FALSE)
}
checks <- data.frame(check=character(), passed=logical())
check <- function(name, condition) {
  checks <<- rbind(checks,data.frame(check=name,passed=isTRUE(condition)))
  stopifnot(isTRUE(condition))
}
save <- function(x,name) write.csv(x,file.path(out,name),row.names=FALSE,na='')
